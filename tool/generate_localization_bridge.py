"""Generate const message references. Translation text lives only in ARB files.
Run after editing resources: python3 tool/generate_localization_bridge.py
Then run: flutter gen-l10n
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / 'lib/l10n/app_fr.arb').read_text())
aliases = json.loads((root / 'lib/l10n/legacy_sources.json').read_text())
static = [key for key in catalog if not key.startswith('@') and not catalog.get('@'+key, {}).get('placeholders')]
quote = lambda s: json.dumps(s, ensure_ascii=False).replace('$', r'\$')
header = '// Generated by tool/generate_localization_bridge.py. Do not edit.\n'
(root / 'lib/core/localization/app_copy.dart').write_text(header + '// Stable references for const widgets; these are not customer data.\nabstract final class AppCopy {\n' + ''.join(f'  static const {key} = "@{key}";\n' for key in static) + '}\n')
(root / 'lib/core/localization/catalog_bridge.dart').write_text(header + 'import "../../l10n/generated/app_messages.dart";\n\nString? resolveMessage(AppMessages messages, String key) => switch(key) {\n' + ''.join(f'  "@{key}" => messages.{key},\n' for key in static) + '  _ => null,\n};\n\n// Transitional adapters for domain/status services returning French labels.\nconst legacyMessageKeys = <String,String>{\n' + ''.join(f'  {quote(source)}: "@{key}",\n' for source, key in aliases.items()) + '};\n')
